'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('api', {
  theme: ipcRenderer.sendSync('theme:current'),
  appReady: () => ipcRenderer.send('app:ready'),
  onCloseRequest: (cb) => ipcRenderer.on('app:close-request', () => cb()),
  closeDecision: (allow) => ipcRenderer.send('app:close-decision', allow),
  info: () => ipcRenderer.invoke('db:info'),
  search: (filters, offset, limit) => ipcRenderer.invoke('ads:search', filters, offset, limit),
  count: (filters) => ipcRenderer.invoke('ads:count', filters),
  timeline: (filters) => ipcRenderer.invoke('ads:timeline', filters),
  summaryState: () => ipcRenderer.invoke('summary:get'),
  onSummary: (cb) => ipcRenderer.on('summary:state', (_e, s) => cb(s)),
  tasks: () => ipcRenderer.invoke('tasks:list'),
  onTask: (cb) => ipcRenderer.on('task:event', (_e, t) => cb(t)),
  facets: (filters) => ipcRenderer.invoke('ads:facets', filters),
  get: (id) => ipcRenderer.invoke('ads:get', id),
  importDialog: () => ipcRenderer.invoke('import:dialog'),
  importFiles: (paths) => ipcRenderer.invoke('import:start', paths),
  removeSource: (name) => ipcRenderer.invoke('source:remove', name),
  datasets: () => ipcRenderer.invoke('datasets:list'),
  datasetSummaries: () => ipcRenderer.invoke('datasets:summary'),
  createDataset: (name, description) => ipcRenderer.invoke('datasets:create', name, description),
  updateDataset: (id, name, description) => ipcRenderer.invoke('datasets:update', id, name, description),
  activateDataset: (id) => ipcRenderer.invoke('datasets:activate', id),
  deleteDataset: (id) => ipcRenderer.invoke('datasets:delete', id),
  reprocessDataset: (id) => ipcRenderer.invoke('datasets:reprocess', id),
  openExternal: (url) => ipcRenderer.invoke('open:external', url),
  pathFor: (file) => webUtils.getPathForFile(file),
  onImport: (cb) => ipcRenderer.on('import:event', (_e, m) => cb(m)),
});
